import Obj2fsHOC from 'obj2fs-hoc'

import Crypto from '../util/crypto'
import config from '../config'

import Transaction from './transaction'
import Account from './account'
import BlockchainError, { ERROR_CODES } from './errors'

// Use dynamic imports for ESM-only packages to work with Jest's CJS environment
// Babel transforms these into Promise-based require() calls
const libp2pCryptoKeys = () => import('@libp2p/crypto/keys')
const libp2pPeerId = () => import('@libp2p/peer-id')

// Use @noble/secp256k1 (externalized in webpack, mocked in Jest)
// v3.1.0 exports: keygen(), signAsync(), verify(), getPublicKey()
const ecrypto = require('@noble/secp256k1')

const nodeCrypto = require('crypto')
const fs = require('fs')
const path = require('path')
const Big = require('big.js')

class Wallet {
  constructor() {
    // this is only one wallet per running application, so it's OK to hard code it here
    this.key = path.resolve(config.STORE.WALLET)

    // Use secp256k1 for both signing and libp2p peer identity
    const { secretKey, publicKey } = ecrypto.keygen()
    this.privateKey = Crypto.bytesToHex(secretKey)
    this.publicKey = Crypto.bytesToHex(publicKey.length === 33
      ? ecrypto.getPublicKey(secretKey, false)
      : publicKey)
  }

  /**
   * Returns the libp2p PeerId derived from this wallet's public key.
   * Used for ENR generation and discv5 peer discovery.
   * @returns {Promise<import('@libp2p/interface').PeerId>}
   */
  async getPeerId() {
    const { publicKeyFromRaw } = await libp2pCryptoKeys()
    const { peerIdFromPublicKey } = await libp2pPeerId()
    // Convert hex public key to raw bytes
    const raw = Crypto.hexToBytes(this.publicKey)
    const libp2pPubKey = publicKeyFromRaw(raw, 'secp256k1')
    return peerIdFromPublicKey(libp2pPubKey)
  }

  /**
   * Sign data using secp256k1 ECDSA with SHA-512.
   * @param {*} data
   * @returns {Promise<string>} hex-encoded signature
   */
  async sign(data) {
    const hash = Crypto.hash(data)
    const msgBytes = Crypto.hexToBytes(hash)
    const privBytes = Crypto.hexToBytes(this.privateKey)
    const sig = await ecrypto.signAsync(msgBytes, privBytes)
    return Crypto.bytesToHex(sig)
  }

  async transactionSignature({ transaction }) {
    const signature = await this.sign([
      transaction.uuid,
      transaction.timestamp,
      transaction.sender,
      transaction.recipient,
      Big(transaction.amount).valueOf(),
      Big(transaction.fee).valueOf(),
    ])
    return signature
  }

  // this method is called to create transaction that goes into transaction pool,
  // there is no other place to create new transaction,
  // at this point the transaction should be signed and never modified.
  // This should be the only way to create transaction
  async createTransaction({ recipient, amount, fee }) {
    const transaction = new Transaction({
      sender: this.publicKey, recipient, amount, fee,
    })
    transaction.signature = await this.transactionSignature({ transaction })
    return transaction
  }

  // this creates a reward transaction for this wallet.
  // This transaction does not have to be added to the pool
  async createRewardTransaction() {
    const transaction = new Transaction({
      sender: this.publicKey, recipient: config.REWARD_ADDRESS, amount: config.REWARD_AMOUNT, fee: 0,
    })
    transaction.signature = await this.transactionSignature({ transaction })
    return transaction
  }

  async createStakeTransaction({ amount, fee }) {
    const transaction = new Transaction({
      sender: this.publicKey, recipient: config.STAKE_ADDRESS, amount, fee,
    })
    transaction.signature = await this.transactionSignature({ transaction })
    return transaction
  }

  // TODO: TOTEST
  async getAccount() {
    const account = await new Account({ publicKey: this.publicKey }).retrieveThrough()
    return account
  }

  /**
   * Strict startup load (CAP-12). Replaces the HOC `retrieveThrough()`:
   * - no wallet file -> persist the key pair generated by the constructor and
   *   return this (first run, the ratified behavior);
   * - wallet file present -> read + JSON.parse + shape checks + cross-derive
   *   the public key from the private key. ANY failure throws a typed
   *   `corrupted-wallet` BlockchainError BEFORE any key field is assigned —
   *   the constructor-generated keys are never silently replaced by a
   *   parseable-but-wrong file, and a corrupt file never falls back to a
   *   fresh identity (fail-fast; recovery is an explicit `restoreBackup`).
   * @returns {Promise<Wallet>} this
   */
  async load() {
    const file = path.resolve(this.key)
    if (!fs.existsSync(file)) {
      try {
        await this.store()
      } catch (error) {
        throw new BlockchainError(
          `Wallet file could not be persisted (${file}): ${error.message}`,
          ERROR_CODES.CORRUPTED_WALLET,
        )
      }
      return this
    }
    let raw
    try {
      raw = fs.readFileSync(file, 'utf8')
    } catch (error) {
      throw new BlockchainError(
        `Wallet file could not be read (${file}): ${error.message}`,
        ERROR_CODES.CORRUPTED_WALLET,
      )
    }
    let stored
    try {
      stored = JSON.parse(raw)
    } catch {
      throw new BlockchainError(
        `Wallet file ${file} is not valid JSON`,
        ERROR_CODES.CORRUPTED_WALLET,
      )
    }
    const problem = storedPairProblem(stored)
    if (problem) {
      throw new BlockchainError(
        `Wallet file ${file} is corrupted: ${problem}`,
        ERROR_CODES.CORRUPTED_WALLET,
      )
    }
    this.privateKey = stored.privateKey
    this.publicKey = stored.publicKey
    return this
  }

  /**
   * Encrypt the key pair into a human-readable backup string (CAP-12).
   * Wire: `succinctcoin-backup-v1:` + base64(salt ‖ iv ‖ ciphertext ‖ tag) —
   * aes-256-gcm under a key scrypt-derived from the password.
   * @param {string} password non-empty passphrase
   * @returns {string} the backup string
   */
  exportBackup(password) {
    assertBackupPassword(password)
    const payload = JSON.stringify({
      v: BACKUP_VERSION,
      privateKey: this.privateKey,
      publicKey: this.publicKey,
    })
    const buffer = encryptBackupPayload(payload, password)
    return `${BACKUP_PREFIX}${buffer.toString('base64')}`
  }

  /**
   * Restore the key pair from an encrypted backup string (CAP-12).
   * SYNCHRONOUS on purpose: it is answered from an `ipcMain.on` handler
   * through `event.returnValue` inside the same dispatch, so nothing in the
   * success path may be awaited. On success the restored pair is assigned
   * AND persisted to the wallet file (byte-identical to what the HOC
   * `store()` writes, but written synchronously) so the recovered identity
   * survives a restart. Any failure throws a typed `invalid-backup`
   * BlockchainError before any assignment or write.
   * @param {string} backup the `succinctcoin-backup-v1:` string
   * @param {string} password the password the backup was exported with
   * @returns {Wallet} this
   */
  restoreBackup(backup, password) {
    assertBackupPassword(password)
    try {
      return this.restoreFromDecoded(backup, password)
    } catch (error) {
      if (error instanceof BlockchainError && error.code === ERROR_CODES.INVALID_BACKUP) {
        throw error
      }
      // Never let a surprise (e.g. a crypto layer throw) escape untyped:
      // the IPC surface promises a typed `invalid-backup` response.
      throw new BlockchainError(
        `Backup restore failed: ${error.message}`,
        ERROR_CODES.INVALID_BACKUP,
      )
    }
  }

  // The restore validation chain, split out of restoreBackup() so both
  // methods stay under the complexity budget. Every failure here is a typed
  // `invalid-backup` thrown before any key assignment or file write.
  restoreFromDecoded(backup, password) {
    const decoded = decodeBackupWire(backup)
    if (!decoded) {
      throw new BlockchainError('Backup is malformed: it is not a decodable succinctcoin-backup-v1 string', ERROR_CODES.INVALID_BACKUP)
    }
    const { salt, iv, ciphertext, tag } = decoded
    const { decrypted, verified } = decryptBackup({ password, salt, iv, ciphertext, tag })
    if (!verified) {
      throw new BlockchainError('Backup could not be authenticated: wrong password or a tampered backup', ERROR_CODES.INVALID_BACKUP)
    }
    const payload = parseBackupPayload(decrypted)
    if (!payload || payload.v !== BACKUP_VERSION) {
      throw new BlockchainError(
        `Backup payload must be a JSON object with version v${BACKUP_VERSION}`,
        ERROR_CODES.INVALID_BACKUP,
      )
    }
    const problem = storedPairProblem(payload)
    if (problem) {
      throw new BlockchainError(`Backup key pair is invalid: ${problem}`, ERROR_CODES.INVALID_BACKUP)
    }
    // Persist the RESTORED pair (not the wallet's current keys) before
    // assigning: a persist failure leaves the wallet untouched (typed error,
    // no half-restored state), and a crash between persist and assign leaves
    // the restored identity on disk, where a restart's load() installs it —
    // never an in-memory-only restore that undoes at restart.
    persistWalletIdentity(this.key, payload.privateKey, payload.publicKey)
    this.privateKey = payload.privateKey
    this.publicKey = payload.publicKey
    return this
  }
}

const BACKUP_PREFIX = 'succinctcoin-backup-v1:'
const BACKUP_VERSION = 1
// Salt(16) + iv(12) + a 1-byte ciphertext + 16-byte auth tag is the smallest
// decodable envelope; anything shorter cannot carry a payload.
const MIN_ENVELOPE_LENGTH = 44

const assertBackupPassword = password => {
  if (typeof password !== 'string' || password.length === 0) {
    throw new BlockchainError('Backup password must be a non-empty string', ERROR_CODES.INVALID_BACKUP)
  }
}

// Returns a human-readable problem description of a would-be key pair, or
// null when the pair is valid. Never throws — even a shape-valid but
// unusable scalar (e.g. an out-of-curve private key) is a PROBLEM, because
// both `load()` and `restoreBackup()` must map it to their typed error.
const storedPairProblem = stored => {
  if (!stored || typeof stored !== 'object') {
    return 'content is not a JSON object'
  }
  if (typeof stored.privateKey !== 'string' || !/^[0-9a-f]{64}$/.test(stored.privateKey)) {
    return 'privateKey is not a 64-character lowercase hex string'
  }
  if (typeof stored.publicKey !== 'string' || !/^04[0-9a-f]{128}$/.test(stored.publicKey)) {
    return 'publicKey is not a 130-character lowercase hex string with the 04 uncompressed prefix'
  }
  let derived
  try {
    derived = Crypto.bytesToHex(ecrypto.getPublicKey(Crypto.hexToBytes(stored.privateKey), false))
  } catch (error) {
    return `privateKey is not a usable secp256k1 key (${error.message})`
  }
  if (derived !== stored.publicKey) {
    return 'publicKey is not derivable from privateKey'
  }
  return null
}

// Writes the given identity to the wallet file under the resolved key.
// The HOC `store()` writes JSON.stringify(this) after deleting the transient
// `key` property; a Wallet instance holds only key/privateKey/publicKey as
// own enumerable properties, so the byte-identical content is exactly this
// explicit object. Written synchronously because the HOC `store()` is async
// and unavailable inside the synchronous `event.returnValue` dispatch.
const persistWalletIdentity = (key, privateKey, publicKey) => {
  const file = path.resolve(key)
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(
    file,
    JSON.stringify({ privateKey, publicKey }),
    'utf8',
  )
}

const deriveBackupKey = (password, salt) => nodeCrypto.scryptSync(
  password,
  salt,
  32,
  { N: 16384, r: 8, p: 1 },
)

const encryptBackupPayload = (payload, password) => {
  const salt = nodeCrypto.randomBytes(16)
  const iv = nodeCrypto.randomBytes(12)
  const cipher = nodeCrypto.createCipheriv('aes-256-gcm', deriveBackupKey(password, salt), iv)
  const ciphertext = Buffer.concat([cipher.update(payload, 'utf8'), cipher.final()])
  const tag = cipher.getAuthTag()
  return Buffer.concat([salt, iv, ciphertext, tag])
}

// Returns the split envelope, or null when the string is not a decodable
// succinctcoin-backup-v1 wire value (wrong/missing prefix, bad base64,
// too short).
const decodeBackupWire = backup => {
  if (typeof backup !== 'string' || !backup.startsWith(BACKUP_PREFIX)) {
    return null
  }
  const encoded = backup.slice(BACKUP_PREFIX.length)
  if (!/^[A-Za-z0-9+/]+={0,2}$/.test(encoded)) {
    return null
  }
  let buffer
  try {
    buffer = Buffer.from(encoded, 'base64')
  } catch {
    return null
  }
  if (buffer.length < MIN_ENVELOPE_LENGTH) return null
  return {
    salt: buffer.subarray(0, 16),
    iv: buffer.subarray(16, 28),
    ciphertext: buffer.subarray(28, buffer.length - 16),
    tag: buffer.subarray(buffer.length - 16),
  }
}

// Decrypt + authenticate the envelope. Never throws for a bad password or a
// flipped byte: GCM reporting is folded into the `verified` flag so the
// caller maps it to the typed `invalid-backup` error.
const decryptBackup = ({ password, salt, iv, ciphertext, tag }) => {
  const decipher = nodeCrypto.createDecipheriv('aes-256-gcm', deriveBackupKey(password, salt), iv)
  decipher.setAuthTag(tag)
  let decrypted
  let verified = true
  try {
    decrypted = Buffer.concat([decipher.update(ciphertext), decipher.final()])
  } catch {
    verified = false
  }
  return { decrypted, verified }
}

// Parse the decrypted payload and enforce the version-capable object shape.
// Returns the payload, or null for `null` / scalars / arrays (a `v: 2`,
// `{}` or `[]` payload all land here and become typed `invalid-backup`).
const parseBackupPayload = decrypted => {
  let payload
  try {
    payload = JSON.parse(decrypted.toString('utf8'))
  } catch {
    return null
  }
  if (!payload || typeof payload !== 'object' || Array.isArray(payload)) {
    return null
  }
  return payload
}

export default Obj2fsHOC(Wallet)
